import { describe, expect, test } from 'bun:test';
import { createRequire } from 'node:module';
import { isAllowedLocalAdminRscRead } from '../tests/nightly/local-admin-rsc-read-boundary';

const require = createRequire(import.meta.url);
const { computeCacheBustingSearchParam, computeLegacyCacheBustingSearchParam } = require(
    'next/dist/shared/lib/router/utils/cache-busting-search-param',
);
const appOrigin = 'http://127.0.0.1:18080';
const allowed = (url: string, method = 'GET', rscHeader: string | undefined = '1', origin: string | undefined = appOrigin) =>
    isAllowedLocalAdminRscRead({ url: new URL(url, appOrigin), method, rscHeader, appOrigin: origin });

describe('local admin framework RSC read boundary', () => {
    test('admits cache keys generated by the installed Next implementation', async () => {
        const current = await computeCacheBustingSearchParam(undefined, undefined, '[]', '/admin');
        const legacy = computeLegacyCacheBustingSearchParam(undefined, undefined, '[]', '/admin');
        expect(allowed(`/admin?_rsc=${current}`)).toBe(true);
        expect(allowed(`/admin?_rsc=${legacy}`)).toBe(true);
        expect(allowed('/admin?_rsc')).toBe(true);
    });

    test('rejects extra, repeated, malformed and API query parameters', () => {
        for (const route of [
            '/admin', '/admin?_rsc=', '/admin?_rsc=a&module=users',
            '/admin?module=users&_rsc=a', '/admin?_rsc=a&_rsc=b',
            '/admin?%5Frsc=a', '/admin?_rsc=%61', '/admin?_rsc=a.b',
            `/admin?_rsc=${'a'.repeat(129)}`, '/admin/?_rsc=a',
            '/api/admin/evaluations?_rsc=a', '/admin?_rsc=a#fragment',
        ]) expect(allowed(route)).toBe(false);
    });

    test('requires the exact admitted local origin, GET method and RSC header', () => {
        expect(allowed('/admin?_rsc=a', 'POST')).toBe(false);
        expect(allowed('/admin?_rsc=a', 'HEAD')).toBe(false);
        expect(allowed('/admin?_rsc=a', 'GET', '0')).toBe(false);
        expect(isAllowedLocalAdminRscRead({ url: new URL('/admin?_rsc=a', appOrigin), method: 'GET', rscHeader: undefined, appOrigin })).toBe(false);
        expect(allowed('http://127.0.0.1:18081/admin?_rsc=a')).toBe(false);
        expect(allowed('http://localhost:18080/admin?_rsc=a')).toBe(false);
        expect(allowed('https://example.invalid/admin?_rsc=a')).toBe(false);
        expect(allowed('http://reader@127.0.0.1:18080/admin?_rsc=a')).toBe(false);
        expect(allowed('/admin?_rsc=a', 'GET', '1', 'https://example.invalid')).toBe(false);
        expect(allowed('/admin?_rsc=a', 'GET', '1', appOrigin + '/other')).toBe(false);
        expect(allowed('/admin?_rsc=a', 'GET', '1', '')).toBe(false);
    });
});
