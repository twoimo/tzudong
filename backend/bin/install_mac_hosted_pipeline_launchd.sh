#!/usr/bin/env bash
# Install a Mac LaunchAgent that runs the same hosted new-video pipeline as GHA.
# Does not start the heavy local worker. Does not enable hosted_apply latch.
# launchd cannot read Documents/Desktop/Downloads unless /bin/bash has Full Disk Access.
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LABEL="dev.tzudong.hosted-new-video"
PLIST="$HOME/Library/LaunchAgents/${LABEL}.plist"
SUPPORT="$HOME/Library/Application Support/tzudong"
LOG_DIR="$HOME/Library/Logs/tzudong"
WRAPPER="$SUPPORT/run-hosted-new-video.sh"
FFMPEG_ROOT="$SUPPORT/runtime/bin"
FFMPEG="$FFMPEG_ROOT/ffmpeg"
SERVICE="gui/$(id -u)/${LABEL}"
if [[ -n "${PYTHON_CMD:-}" ]]; then
  PYTHON="$PYTHON_CMD"
elif [[ -x "$REPO_ROOT/.venv/bin/python" ]]; then
  PYTHON="$REPO_ROOT/.venv/bin/python"
else
  PYTHON="/usr/bin/python3"
fi
# Validate before replacing either installed file. Never unload another writer.
"$PYTHON" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)' >/dev/null 2>&1 || {
  echo "python_runtime_unavailable" >&2
  exit 1
}
FREEZE_STATE="${G037_WRITE_FREEZE:-active}"
case "$FREEZE_STATE" in
  active|cleared) ;;
  *) echo 'invalid_write_freeze_state' >&2; exit 2 ;;
esac
if [[ ! -d "$FFMPEG_ROOT" || -L "$FFMPEG_ROOT" || ! -f "$FFMPEG" || -L "$FFMPEG" || ! -x "$FFMPEG" ]]; then
  echo 'ffmpeg_runtime_unavailable' >&2
  exit 1
fi
assert_agent_absent() {
  local status
  if launchctl print "$SERVICE" >/dev/null 2>&1; then
    # Even an idle registered agent can start between this check and bootout.
    echo 'launch_agent_already_registered' >&2
    exit 1
  else
    status=$?
  fi
  # launchctl's service-not-found result; every unknown read failure is closed.
  if [[ "$status" -ne 113 ]]; then
    echo 'launch_agent_state_unconfirmed' >&2
    exit 1
  fi
}
assert_agent_absent
STAGING="$(mktemp -d "${TMPDIR:-/tmp}/tzudong-hosted-install.XXXXXX")"
trap 'rm -rf "$STAGING"' EXIT
STAGED_WRAPPER="$STAGING/run-hosted-new-video.sh"
STAGED_PLIST="$STAGING/${LABEL}.plist"
cat > "$STAGED_WRAPPER" <<EOF
#!/bin/bash
set -euo pipefail
export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin"
export TZUDONG_REPO_ROOT=$(printf '%q' "$REPO_ROOT")
export TZUDONG_PIPELINE_SOURCE="mac"
export G037_WRITE_FREEZE="${FREEZE_STATE}"
export PYTHON_CMD=$(printf '%q' "$PYTHON")
export TZUDONG_LAAJ_PROVIDER="gemini"
export TZUDONG_HOSTED_DATA_PLANE_APPROVED="1"
export ALLOW_CUSTOM_FFMPEG="1"
export FFMPEG_PATH=$(printf '%q' "$FFMPEG")
export FFMPEG_TRUSTED_ROOT=$(printf '%q' "$FFMPEG_ROOT")
if [[ -x "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" ]]; then
  export PUPPETEER_EXECUTABLE_PATH="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
fi
cd "\$TZUDONG_REPO_ROOT"
echo "\$(date -u +%Y-%m-%dT%H:%M:%SZ) start source=mac freeze=\${G037_WRITE_FREEZE} limit=3"
set +e
$(printf '%q' "$PYTHON") "\$TZUDONG_REPO_ROOT/backend/bin/run_hosted_new_video_pipeline.py" --channel tzuyang --limit 3 --review-automation
pipeline_exit=\$?
set -e
echo "\$(date -u +%Y-%m-%dT%H:%M:%SZ) end exit=\${pipeline_exit}"
exit "\${pipeline_exit}"
EOF
# plistlib escapes source/HOME paths and validates the actual generated bytes.
if ! "$PYTHON" - "$STAGED_PLIST" "$LABEL" "$SUPPORT" "$WRAPPER" "$REPO_ROOT" "$FREEZE_STATE" "$LOG_DIR" >/dev/null 2>&1 <<'PY'
import pathlib
import plistlib
import sys

destination, label, support, wrapper, repo, freeze, logs = sys.argv[1:]
# The cadence preflight reads this exact XML; consume the same values below.
calendar = plistlib.loads(b'''<plist version="1.0"><dict>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Hour</key>
    <integer>5</integer>
    <key>Minute</key>
    <integer>15</integer>
  </dict>
</dict></plist>''')
config = {
    'Label': label,
    'WorkingDirectory': support,
    'ProgramArguments': ['/bin/bash', wrapper],
    'EnvironmentVariables': {
        'TZUDONG_PIPELINE_SOURCE': 'mac', 'TZUDONG_REPO_ROOT': repo,
        'G037_WRITE_FREEZE': freeze,
    },
    'StartCalendarInterval': calendar['StartCalendarInterval'],
    'StandardOutPath': str(pathlib.Path(logs) / 'mac-hosted-new-video.log'),
    'StandardErrorPath': str(pathlib.Path(logs) / 'mac-hosted-new-video.err.log'),
}
path = pathlib.Path(destination)
path.write_bytes(plistlib.dumps(config))
if plistlib.loads(path.read_bytes()) != config:
    raise ValueError('generated_launch_agent_invalid')
PY
then
  echo 'generated_launch_agent_invalid' >&2
  exit 1
fi
if ! /bin/bash -n "$STAGED_WRAPPER" >/dev/null 2>&1; then
  echo 'generated_launch_agent_invalid' >&2
  exit 1
fi
chmod 755 "$STAGED_WRAPPER"
chmod 644 "$STAGED_PLIST"
assert_agent_absent
mkdir -p "$HOME/Library/LaunchAgents" "$SUPPORT" "$LOG_DIR" "$REPO_ROOT/backend/log/cron"
mv "$STAGED_WRAPPER" "$WRAPPER"
mv "$STAGED_PLIST" "$PLIST"
launchctl bootstrap "gui/$(id -u)" "$PLIST"
echo "installed ${PLIST}"
echo "wrapper=${WRAPPER}"
echo "logs=${LOG_DIR}"
echo "source=mac schedule=05:15 local evaluate+pending-apply+review-automation limit=3"
echo "write_freeze=${FREEZE_STATE}"
echo "tcc=grant_full_disk_access_to_/bin/bash if repo is under Documents"
